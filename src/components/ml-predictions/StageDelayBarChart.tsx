import React from 'react';
import { BarChart3, Info } from 'lucide-react';
import { StagePredictionItem, StageName } from '../../types';

interface StageDelayBarChartProps {
  stages: StagePredictionItem[];
  selectedStage?: StageName | null;
  onSelectStage: (stage: StageName) => void;
}

export const StageDelayBarChart: React.FC<StageDelayBarChartProps> = ({
  stages,
  selectedStage,
  onSelectStage,
}) => {
  return (
    <div className="bg-white p-5 rounded-2xl border border-gray-200 shadow-2xs space-y-4 flex flex-col justify-between">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <h2 className="text-sm font-bold text-gray-900 flex items-center gap-2">
            <BarChart3 className="w-4 h-4 text-[#0B3520]" />
            <span>Stage-wise Delay Probability Chart</span>
          </h2>
          <p className="text-xs text-gray-500">
            Comparative delay likelihood distribution generated by ML inference ensemble
          </p>
        </div>

        {/* Legend */}
        <div className="hidden sm:flex items-center gap-3 text-[11px] font-medium text-gray-600">
          <div className="flex items-center gap-1.5">
            <span className="w-2.5 h-2.5 rounded-xs bg-emerald-500" />
            <span>Low (&lt;40%)</span>
          </div>
          <div className="flex items-center gap-1.5">
            <span className="w-2.5 h-2.5 rounded-xs bg-amber-500" />
            <span>Medium (40-70%)</span>
          </div>
          <div className="flex items-center gap-1.5">
            <span className="w-2.5 h-2.5 rounded-xs bg-red-600" />
            <span>High (&gt;70%)</span>
          </div>
        </div>
      </div>

      {/* Horizontal Bars Container */}
      <div className="space-y-3 pt-2">
        {stages.map((stg) => {
          const isSelected = selectedStage === stg.stage;
          const prob = stg.delayProbability;
          const barColor =
            prob >= 70
              ? 'bg-red-600'
              : prob >= 40
              ? 'bg-amber-500'
              : 'bg-emerald-600';

          return (
            <div
              key={stg.stage}
              onClick={() => onSelectStage(stg.stage)}
              className={`p-2.5 rounded-xl transition-all cursor-pointer border ${
                isSelected
                  ? 'border-[#0B3520] bg-emerald-50/60 shadow-xs ring-1 ring-[#0B3520]'
                  : 'border-transparent hover:bg-gray-50 hover:border-gray-200'
              }`}
            >
              <div className="flex items-center justify-between text-xs mb-1.5">
                <div className="flex items-center gap-2">
                  <span className="font-mono text-[10px] font-bold text-gray-400">
                    0{stg.stageNumber}
                  </span>
                  <span className="font-bold text-gray-800">{stg.stage}</span>
                </div>

                <div className="flex items-center gap-3 font-mono text-xs">
                  <span className="text-gray-500 font-sans text-[11px]">
                    +{stg.expectedDelayMonths} mo
                  </span>
                  <span className="font-bold text-gray-900 w-12 text-right">
                    {prob.toFixed(1)}%
                  </span>
                </div>
              </div>

              {/* Progress Bar with Guidelines */}
              <div className="relative w-full bg-gray-100 h-3 rounded-full overflow-hidden">
                {/* Guidelines */}
                <div className="absolute inset-0 flex pointer-events-none">
                  <div className="w-[40%] border-r border-gray-300/60 h-full" />
                  <div className="w-[30%] border-r border-gray-300/60 h-full" />
                  <div className="w-[30%] h-full" />
                </div>

                {/* Animated Fill */}
                <div
                  className={`h-full rounded-full transition-all duration-700 ${barColor}`}
                  style={{ width: `${Math.min(100, prob)}%` }}
                />
              </div>
            </div>
          );
        })}
      </div>

      {/* Threshold Ruler */}
      <div className="pt-2 border-t border-gray-100 flex justify-between text-[10px] font-mono text-gray-400 px-2">
        <span>0%</span>
        <span>25%</span>
        <span className="text-amber-600 font-bold">50% (Medium Alert)</span>
        <span className="text-red-600 font-bold">75% (Critical Threshold)</span>
        <span>100%</span>
      </div>
    </div>
  );
};
